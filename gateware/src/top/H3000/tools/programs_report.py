"""Format the emulator's program report as PROGRAMS.md.

usage: python programs_report.py <report.tsv>... <out.md>

The report comes from the PC runner (emu/src/bin/h3000-host.rs, `report`):
it loads every program of the H3500 ROM set and records what the front panel
shows: P (program), G (soft key labels of each parameter page), S (Soft
Functions 1-4), M (modulation patch of each patchable parameter), E (error).
"""

import re
import sys
from collections import defaultdict

DEFAULT_SOFT = re.compile(r'Soft (\d) is " [Kk]nob \1 " Sens=\s*100 Pol= \+$')
SOFT_RE = re.compile(r'Soft (\d) is "(.{8})" Sens=\s*(-?\d+) Pol= (\S+)')
RANGE_RE = re.compile(r"mod range:\s*(-?[\d.]+)\[\s*(-?[\d.]+)/note\]")
CHANNEL_RE = re.compile(r"\s+Ch\+\s*(\d+)$")

# Patch sources that are not MIDI.
UNREADABLE = "(unreadable: the display shows ROM bytes)"
INTERNAL = ("Soft Function", "Function Gen", UNREADABLE)


def parse(paths):
    """Later files take precedence: a program reported again (e.g. retried
    on its own) replaces its earlier entry and errors."""
    progs = {}
    errors = {}
    for path in paths:
        p, e = parse_one(path)
        for num in set(p) | set(e):
            progs.pop(num, None)
            errors.pop(num, None)
        progs.update(p)
        errors.update(e)
    return ([progs[n] for n in sorted(progs)],
            [(n, w) for n in sorted(errors) for w in errors[n]])


def parse_one(path):
    progs = {}
    errors = defaultdict(list)
    cur = None
    for line in open(path, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        kind = f[0]
        if kind == "P":
            cur = {"num": int(f[1]), "name": f[2], "pages": [], "soft": [], "patches": []}
            progs[cur["num"]] = cur
        elif kind == "G":
            cur["pages"].append((f[1:] + [""] * 4)[:4])
        elif kind == "S":
            cur["soft"].append(f[1])
        elif kind == "M":
            param, source = f[1], f[2]
            if not source.strip():
                # The patch page shows "<param> U (" and ROM bytes instead
                # of "-> <source>" (in the presets' own data: the same with
                # every ROM set).
                source = UNREADABLE
            if source != "Patch is disabled":
                rng = RANGE_RE.search(f[3]) if len(f) > 3 else None
                cur["patches"].append((param, source, rng.groups() if rng else None))
        elif kind == "E":
            errors[int(f[1])].append(f[2])
    return progs, errors


def program_change(num):
    """How program `num` is called up with a MIDI program change (Pgm=ID)."""
    if num <= 127:
        return "%d (any bank)" % num
    return "Bank=%d, program change %d" % (num // 100, num % 100)


def md(text):
    return text.replace("|", "\\|").replace("*", "\\*").replace("_", "\\_") or " "


def source_text(source):
    m = CHANNEL_RE.search(source)
    if m:
        base = source[:m.start()].strip()
        if base.isdigit():
            base = "unnamed source " + base
        ch = int(m.group(1))
        return base + (" (base channel)" if ch == 0 else " (base channel + %d)" % ch)
    # Soft Function 2   " speed  " -> Soft Function 2 "speed"
    source = re.sub(r'"\s*([^"]*?)\s*"', r'"\1"', source)
    return re.sub(r"\s+", " ", source)


def is_midi(source):
    return not source.startswith(INTERNAL)


def main():
    progs, errors = parse(sys.argv[1:-1])
    failed = {num for num, _ in errors}
    missing = failed - {p["num"] for p in progs}
    assert not missing, "programs not reported at all: %s" % sorted(missing)
    out = []
    w = out.append

    n_patched = sum(1 for p in progs if p["patches"])
    n_midi = sum(1 for p in progs if any(is_midi(s) for _, s, _ in p["patches"]))
    sources = defaultdict(int)
    for p in progs:
        for _, s, _ in p["patches"]:
            # Soft Functions by number (their names differ per program).
            sources[re.sub(r'^(Soft Function \d).*', r"\1", source_text(s))] += 1

    w("# H3500 programs")
    w("")
    w("Every program of the H3500 ROM set this project builds (OS 2.17 with all")
    w("five program ROMs: %d programs), with the soft key parameters of each" % len(progs))
    w("parameter page, its Soft Functions and its modulation patches, which include")
    w("its MIDI controller assignments.")
    w("")
    w("This was generated by loading each program in the emulator")
    w("(`emu/src/bin/h3000-host.rs`, command `report`; formatted by")
    w("`tools/programs_report.py`) and reading the front panel, so it shows what")
    w("the original firmware shows, abbreviations included. The factory state")
    w("applies: every program as it comes out of the ROMs, MIDI on all channels.")
    w("")
    w("## Calling programs up over MIDI")
    w("")
    w("With the factory MIDI setup (SETUP, \"MIDI Program Change Functions\":")
    w("Pgm=ID, Pgm=On, Bank=0) a program change selects a program by its number:")
    w("")
    w("- Program change 100-127 loads program 100-127, whatever the bank.")
    w("- Program change 0-99 loads program *bank* x 100 + *n*: with Bank=2,")
    w("  program change 22 loads 222. The bank is set on that SETUP page only;")
    w("  MIDI bank select (CC 0 / CC 32) is ignored.")
    w("- Pgm=Map instead uses the MIDI map table (the Map soft key on the same")
    w("  page), which is empty in the factory state.")
    w("")
    w("Each program below lists the program change that calls it up. Changing")
    w("programs from the front panel is described in README.md.")
    w("")
    w("## Reading the entries")
    w("")
    w("- **Soft keys**: the four soft key labels of each parameter page, in the")
    w("  order PAGE> steps through them. Labels such as `quan=off` show a")
    w("  setting's state; `levels` and `expert` lead to further pages (input /")
    w("  output levels, expert parameters), which are not listed.")
    w("- **Soft Functions**: the H3500's four per-program control knobs (name,")
    w("  sensitivity, polarity), shown when the program defines them. A patch")
    w("  routes a Soft Function to one or more parameters.")
    w("- **Patches**: each parameter with a modulation source assigned in the")
    w("  program. MIDI sources respond on the base MIDI channel (SETUP, \"MIDI")
    w("  Functions\", Base=1) plus the offset shown; *range* is the modulation")
    w("  depth in the parameter's units, *per note* the extra depth per MIDI")
    w("  note for note-dependent sources.")
    w("")
    w("%d programs have patches; %d of them respond to MIDI controllers, wheels," % (n_patched, n_midi))
    w("pedals or notes. Sources used, with the number of patches:")
    w("")
    w("| Source | Patches |")
    w("|---|---|")
    for s, n in sorted(sources.items(), key=lambda kv: (-kv[1], kv[0])):
        w("| %s | %d |" % (md(s), n))
    w("")
    w("The H3500 names controllers by their standard MIDI meaning:")
    w("")
    w("| H3500 source | MIDI message |")
    w("|---|---|")
    w("| Modulation Wheel | CC 1 |")
    w("| Foot Controller | CC 4 |")
    w("| Damper Pedal | CC 64 (sustain) |")
    w("| GP Controller # 1-4 / # 5-8 | CC 16-19 / CC 80-83 (general purpose) |")
    w("| Global Pressure | channel aftertouch |")
    w("| Pitch Wheel only / Pitch Wheel Positive | pitch bend (full / upward half) |")
    w("| Last Note, High Note, Note Offset, Notes Down, Last Note Velocity, Note *n* | note on / off |")
    w("| MIDI Clock Period | the tempo of incoming MIDI clock |")
    w("")
    w("Other names (e.g. `Undefined Small= 83`) are as the H3500 displays them.")
    w("Function Generator sources are the H3500's internal LFO / envelope")
    w("(SETUP, \"Modulation of Parameters\", FuncGen), not MIDI.")
    w("")

    # Index.
    w("## Index")
    w("")
    w("| No. | Name | MIDI program change | Soft keys, first page | MIDI patches |")
    w("|---|---|---|---|---|")
    for p in progs:
        first = " / ".join(x for x in (p["pages"][0] if p["pages"] else []) if x)
        midi = sorted({source_text(s).split(" (")[0] for _, s, _ in p["patches"] if is_midi(s)})
        w("| [%d](#p%d) | %s | %s | %s | %s |" % (
            p["num"], p["num"], md(p["name"]), program_change(p["num"]), md(first),
            md(", ".join(midi)) if midi else ""))
    w("")

    # Details, grouped by hundreds.
    group = None
    for p in progs:
        g = p["num"] // 100
        if g != group:
            group = g
            w("## Programs %d00-%d99" % (g, g))
            w("")
        w('<a id="p%d"></a>' % p["num"])
        w("")
        w("### %d %s" % (p["num"], md(p["name"])))
        w("")
        w("MIDI program change: %s" % program_change(p["num"]))
        w("")
        if p["pages"]:
            w("| Page | Soft 1 | Soft 2 | Soft 3 | Soft 4 |")
            w("|---|---|---|---|---|")
            for i, page in enumerate(p["pages"], 1):
                w("| %d | %s |" % (i, " | ".join(md(x) for x in page)))
            w("")
        softs = [s for s in p["soft"] if not DEFAULT_SOFT.search(s)]
        if softs:
            w("Soft Functions:")
            w("")
            for s in p["soft"]:
                m = SOFT_RE.search(s)
                if m:
                    n, name, sens, pol = m.groups()
                    polarity = {"+": "positive", "-": "negative", "+-": "bipolar"}.get(pol, pol)
                    w("- Soft %s: %s (sensitivity %s, %s)" % (n, md(name.strip()), sens, polarity))
                else:
                    w("- %s" % md(s))
            w("")
        if p["patches"]:
            w("Patches:")
            w("")
            w("| Parameter | Source | Range | Per note |")
            w("|---|---|---|---|")
            for param, source, rng in p["patches"]:
                r, per = rng if rng else ("", "")
                w("| %s | %s | %s | %s |" % (md(param), md(source_text(source)), r, per))
            w("")
        elif p["num"] in failed:
            w("Soft Functions and patches: not read. After loading this program the")
            w("emulated H3500 stops answering SETUP and the soft keys.")
            w("")
        else:
            w("No modulation patches.")
            w("")

    with open(sys.argv[-1], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("%d programs, %d with patches, %d with MIDI patches, %d errors" % (
        len(progs), n_patched, n_midi, len(errors)))


if __name__ == "__main__":
    main()
